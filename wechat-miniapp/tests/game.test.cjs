const assert = require('assert')
const { player, newRoom, publicRoom, act } = require('../cloudfunctions/game/game')

const a = player('openid-a', 'A')
const b = player('openid-b', 'B')
const room = newRoom('ABC234', a, 'boy', 5)
room.players.push(b)

act(room, a, 'next', {})
assert.equal(room.phase, 'drawing')
act(room, a, 'draw', { round: room.round.id })
assert.equal(room.phase, 'describing')
assert.equal(publicRoom(room, a).round.target, null, 'guesser must not receive the target')
assert.equal(publicRoom(room, a).round.suggestions.length, 0, 'guesser must not receive suggestions')
assert.equal(typeof publicRoom(room, b).round.target, 'number')
assert.equal(publicRoom(room, b).round.suggestions.length, 4)

act(room, b, 'publish', { round: room.round.id, text: '自定义情境', revision: 1 })
assert.equal(room.phase, 'guessing')
act(room, a, 'guess', { round: room.round.id, score: room.round.target })
assert.equal(room.phase, 'results')
assert.equal(room.round.matched, true)
assert.equal(a.wins, 1)
assert.equal(b.wins, 1)

act(room, a, 'next', {})
assert.equal(room.round.guesser, b.id, 'two players should swap roles')
assert.equal(room.round.describer, a.id)
console.log('TEN BUT mini-program game tests passed')
